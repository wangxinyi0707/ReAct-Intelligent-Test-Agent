def build_rag_prompt(question, context):
    """
    构建 RAG 问答场景的提示词，基于给定的旅游知识回答用户问题
    :param question: 用户提出的旅游相关问题
    :param context: 检索到的旅游知识上下文
    :return: 完整的提示词字符串
    """
    return f"""
你是一名专业的旅游规划 AI 助手，擅长结合专业旅游知识解答各类旅游相关问题。
请严格按照以下要求回答用户问题：
1. 真实性优先：严禁编造任何不存在的旅游信息（如景点位置、开放时间、门票价格、交通路线等）。
2. 上下文优先：优先使用提供的旅游知识进行回答，不随意扩展无关内容。
3. 模糊处理：若提供的知识不足以回答用户问题，需明确告知“现有知识不足，无法为你解答该问题”，不得猜测作答。
4. 简洁准确：回答需逻辑清晰、重点突出，语言通俗易懂，符合旅游咨询的实用场景。

旅游知识上下文：
{context}

用户问题：
{question}

请生成详细、准确的回答：
"""


def build_plan_prompt(destination, days, budget, preference, knowledge):
    """
    构建旅行计划生成场景的提示词，结合用户需求和旅游知识生成完整旅行计划
    :param destination: 旅行目的地
    :param days: 旅行总天数（整数）
    :param budget: 旅行总预算（包含单位，如“5000元”“8000元/人”）
    :param preference: 用户旅行偏好（如“亲子游”“美食打卡”“自然风光”“人文古迹”等）
    :param knowledge: 检索到的目的地相关旅游知识（景点、美食、交通等）
    :return: 完整的提示词字符串
    """
    return f"""
你是一名资深旅行规划师，拥有丰富的国内外旅行规划经验，擅长结合用户需求和目的地实际情况，生成合理、实用、贴合预算的旅行计划。
请根据以下用户需求和参考旅游知识，生成一份详细的旅行计划，输出内容需结构清晰、重点明确，符合旅行出行的实际场景。

用户旅行需求：
1. 旅行目的地：{destination}
2. 旅行总天数：{days}天
3. 旅行总预算：{budget}
4. 旅行偏好：{preference}

参考旅游知识（优先参考，可结合常识补充合理内容）：
{knowledge}

旅行计划输出要求（严格按照以下板块呈现，每个板块需有具体内容，避免空泛）：
1. 每日行程：按天数拆分，明确每天的行程安排（如“Day1：抵达目的地→入住酒店→下午游览 XX 景点→晚上品尝当地美食”），标注各环节的大致时间。
2. 景点安排：列出行程中涉及的核心景点，简要说明景点特色、开放时间、门票价格（若有），结合用户偏好突出重点景点。
3. 美食推荐：推荐目的地当地特色美食，说明美食特点、推荐店铺（若有）、大致价格，贴合旅行预算。
4. 交通建议：明确各环节的交通方式（如飞机、高铁、地铁、打车、公交等），说明交通路线、大致耗时和费用，兼顾便捷性和性价比。
5. 注意事项：结合目的地实际情况，给出出行必备物品、当地风俗习惯、天气注意事项、安全提示等实用内容。

请生成完整旅行计划：
"""
